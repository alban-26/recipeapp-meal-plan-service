package com.myapp.mealplan.adapter;

import com.my.common.api.UserId;
import com.myapp.mealplan.adapter.database.recipe.RecipeInfoEntity;
import com.myapp.mealplan.adapter.database.recipe.RecipeIngredientEntity;
import com.myapp.mealplan.adapter.messaging.recipe.RecipeCreatedEvent;
import com.myapp.mealplan.domain.model.recipe.*;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.NotSupportedException;
import org.apache.commons.lang3.NotImplementedException;
import org.openapitools.model.RecipeDto;

import java.util.Collection;
import java.util.List;

@ApplicationScoped
public class RecipeInfoConverterImpl implements RecipeInfoConverter {
    @Override
    public RecipeInfo eventToDomain(RecipeCreatedEvent recipeCreatedEvent) {
        Recipe recipe = new Recipe(new RecipeId(recipeCreatedEvent.getId()), recipeCreatedEvent.getName(), recipeCreatedEvent.getUserId());
        return new RecipeInfo(recipe, recipeCreatedEvent.getPortions(), createRecipeIngredientsFromEvents(recipeCreatedEvent.getIngredients()));
    }

    @Override
    public RecipeCreatedEvent domainToEvent(RecipeInfo recipeInfo) {
        return null;
    }

    @Override
    public RecipeInfo entityToDomain(RecipeInfoEntity recipeInfoEntity) {
        Recipe recipe = new Recipe(new RecipeId(recipeInfoEntity.getId()), recipeInfoEntity.getName(), new UserId(recipeInfoEntity.getUserId()));
        return new RecipeInfo(recipe, recipeInfoEntity.getPortions(), createRecipeIngredientsFromEntities(recipeInfoEntity.getRecipeIngredients()));
    }

    private static Collection<RecipeIngredient> createRecipeIngredientsFromEntities(List<RecipeIngredientEntity> entities) {
        return entities.stream().map(e -> new RecipeIngredient(new Ingredient(e.getIngredientName(), ProductCategory.valueOf(e.getIngredientCategory())), e.getTotalQuantity(), Unit.fromAbbreviation(e.getUnit()))).toList();
    }

    private static Collection<RecipeIngredient> createRecipeIngredientsFromEvents(List<RecipeIngredient> events) {
        return events.stream().map(dto -> new RecipeIngredient(new Ingredient(dto.ingredient().name(), ProductCategory.valueOf(dto.ingredient().productCategory().name())), dto.quantity(), Unit.fromAbbreviation(dto.unit().name()))).toList();
    }


    @Override
    public RecipeInfoEntity domainToEntity(RecipeInfo recipeInfo) {
        return new RecipeInfoEntity(recipeInfo.id().id(), recipeInfo.name(), recipeInfo.portions(), recipeInfo.userId().value(), createRecipeIngredientEntities(recipeInfo.recipeIngredients(), recipeInfo.id()));
    }


    private static List<RecipeIngredientEntity> createRecipeIngredientEntities(Collection<RecipeIngredient> ingredients, RecipeId recipeId) {
        return ingredients.stream().map(ri -> {
            RecipeIngredientEntity e = new RecipeIngredientEntity();
            e.setId(0L); // generated by DB
            e.setRecipeId(recipeId.id());

            // Leave ingredientId null → repository resolves it
            e.setIngredientId(0L);

            e.setIngredientName(ri.ingredient().name());
            e.setIngredientCategory(ri.ingredient().productCategory().name());
            e.setTotalQuantity(ri.quantity());
            e.setUnit(ri.unit().name());
            return e;
        }).toList();
    }

    @Override
    public Recipe dtoToDomain(RecipeDto recipeDto) {
        throw new NotImplementedException("");
    }

    @Override
    public RecipeDto domainToDto(Recipe recipe) {
        return new RecipeDto(recipe.id().id(), recipe.name());
    }
}
